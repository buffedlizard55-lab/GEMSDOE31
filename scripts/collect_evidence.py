def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def copy_legacy_cache(cache: Path) -> dict:
    copied = {}
    if not cache.is_dir():
        return copied
    for name, dest in LEGACY_CACHE_FILES.items():
        source = cache / name
        if not source.is_file() or source.stat().st_size > MAX_BYTES:
            continue
        target = ROOT / dest
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        copied[name] = {"path": dest, "bytes": source.stat().st_size}
    return copied


def inventory() -> list[dict]:
    rows = []
    for path in sorted((ROOT / "evidence").rglob("*")):
        if not path.is_file() or path.name in ("data_preparation.json",):
            continue
        rows.append({"path": str(path.relative_to(ROOT)), "bytes": path.stat().st_size,
                     "sha256": sha256(path)})
    return rows


